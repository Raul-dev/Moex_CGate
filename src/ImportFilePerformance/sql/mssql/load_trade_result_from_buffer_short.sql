      [eveopenamount] nvarchar(512) '$[61]',
      [eveopenprice] nvarchar(512) '$[62]',
      [evelastvolume] nvarchar(512) '$[63]',
      [evelastamount] nvarchar(512) '$[64]',
      [evelastprice] nvarchar(512) '$[65]',
      [evemaxdealprice] nvarchar(512) '$[66]',
      [evemindealprice] nvarchar(512) '$[67]',
      [evetotalvolume] nvarchar(512) '$[68]',
      [evetotalamount] nvarchar(512) '$[69]',
      [evetotalcount] nvarchar(512) '$[70]',
      [evewaprice] nvarchar(512) '$[71]',
