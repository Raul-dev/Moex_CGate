CREATE OR ALTER PROCEDURE dbo.load_trade_result_from_buffer_short_typed
  @SessionId bigint = 0
AS
BEGIN
  SET NOCOUNT ON;
  INSERT INTO dbo.stg_trade_result_typed_target (
    [tradedate], [securityid], [isin], [secshortname], [issuername], [seccategory], [quotelist], [currencyid], [seccurrencyid], [facevalue], [settlementcurrency], [accruedinterest], [isaddress], [setttype], [trademode], [totalvolume], [totalamount], [totaldealcount], [maxdealprice], [mindealprice], [closeprice], [prevclose], [trendclose], [waprice], [marketprice2], [mp2volume], [marketprice3], [mp3volume], [currentprice], [firstcurrentprice], [trendcurrentprice], [averagedailyvolume], [clearingprice], [trendclearingprice], [mornopenvolume], [mornopenamount], [mornopenprice], [mornlastvolume], [mornlastamount], [mornlastprice], [mornmaxdealprice], [mornmindealprice], [morntotalvolume], [morntotalamount], [morntotalcount], [mornwaprice], [morncurrentprice], [mainopenvolume], [mainopenamount], [mainopenprice], [mainlastvolume], [mainlastamount], [mainlastprice], [mainmaxdealprice], [mainmindealprice], [maintotalvolume], [maintotalamount], [maintotalcount], [mainwaprice], [maincurrentprice], [eveopenvolume], [eveopenamount], [eveopenprice], [evelastvolume], [evelastamount], [evelastprice], [evemaxdealprice], [evemindealprice], [evetotalvolume], [evetotalamount], [evetotalcount], [evewaprice], [evecurrentprice]
  )
  SELECT
    TRY_CONVERT(date, NULLIF(LTRIM(RTRIM(j.[tradedate])), '')) AS [tradedate],
    CONVERT(nvarchar(512), j.[securityid]) AS [securityid],
    CONVERT(nvarchar(512), j.[isin]) AS [isin],
    CONVERT(nvarchar(512), j.[secshortname]) AS [secshortname],
    CONVERT(nvarchar(512), j.[issuername]) AS [issuername],
    CONVERT(nvarchar(512), j.[seccategory]) AS [seccategory],
    CONVERT(nvarchar(512), j.[quotelist]) AS [quotelist],
    CONVERT(nvarchar(512), j.[currencyid]) AS [currencyid],
    CONVERT(nvarchar(512), j.[seccurrencyid]) AS [seccurrencyid],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[facevalue], ',', '.'))), '')) AS [facevalue],
    CONVERT(nvarchar(512), j.[settlementcurrency]) AS [settlementcurrency],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[accruedinterest], ',', '.'))), '')) AS [accruedinterest],
    CONVERT(nvarchar(512), j.[isaddress]) AS [isaddress],
    CONVERT(nvarchar(512), j.[setttype]) AS [setttype],
    CONVERT(nvarchar(512), j.[trademode]) AS [trademode],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[totalvolume], ',', '.'))), '')) AS [totalvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[totalamount], ',', '.'))), '')) AS [totalamount],
    TRY_CONVERT(bigint, NULLIF(LTRIM(RTRIM(REPLACE(j.[totaldealcount], ',', '.'))), '')) AS [totaldealcount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[maxdealprice], ',', '.'))), '')) AS [maxdealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mindealprice], ',', '.'))), '')) AS [mindealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[closeprice], ',', '.'))), '')) AS [closeprice],
    CONVERT(nvarchar(512), j.[prevclose]) AS [prevclose],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[trendclose], ',', '.'))), '')) AS [trendclose],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[waprice], ',', '.'))), '')) AS [waprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[marketprice2], ',', '.'))), '')) AS [marketprice2],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mp2volume], ',', '.'))), '')) AS [mp2volume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[marketprice3], ',', '.'))), '')) AS [marketprice3],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mp3volume], ',', '.'))), '')) AS [mp3volume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[currentprice], ',', '.'))), '')) AS [currentprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[firstcurrentprice], ',', '.'))), '')) AS [firstcurrentprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[trendcurrentprice], ',', '.'))), '')) AS [trendcurrentprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[averagedailyvolume], ',', '.'))), '')) AS [averagedailyvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[clearingprice], ',', '.'))), '')) AS [clearingprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[trendclearingprice], ',', '.'))), '')) AS [trendclearingprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornopenvolume], ',', '.'))), '')) AS [mornopenvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornopenamount], ',', '.'))), '')) AS [mornopenamount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornopenprice], ',', '.'))), '')) AS [mornopenprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornlastvolume], ',', '.'))), '')) AS [mornlastvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornlastamount], ',', '.'))), '')) AS [mornlastamount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornlastprice], ',', '.'))), '')) AS [mornlastprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornmaxdealprice], ',', '.'))), '')) AS [mornmaxdealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornmindealprice], ',', '.'))), '')) AS [mornmindealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[morntotalvolume], ',', '.'))), '')) AS [morntotalvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[morntotalamount], ',', '.'))), '')) AS [morntotalamount],
    TRY_CONVERT(bigint, NULLIF(LTRIM(RTRIM(REPLACE(j.[morntotalcount], ',', '.'))), '')) AS [morntotalcount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mornwaprice], ',', '.'))), '')) AS [mornwaprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[morncurrentprice], ',', '.'))), '')) AS [morncurrentprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainopenvolume], ',', '.'))), '')) AS [mainopenvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainopenamount], ',', '.'))), '')) AS [mainopenamount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainopenprice], ',', '.'))), '')) AS [mainopenprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainlastvolume], ',', '.'))), '')) AS [mainlastvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainlastamount], ',', '.'))), '')) AS [mainlastamount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainlastprice], ',', '.'))), '')) AS [mainlastprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainmaxdealprice], ',', '.'))), '')) AS [mainmaxdealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainmindealprice], ',', '.'))), '')) AS [mainmindealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[maintotalvolume], ',', '.'))), '')) AS [maintotalvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[maintotalamount], ',', '.'))), '')) AS [maintotalamount],
    TRY_CONVERT(bigint, NULLIF(LTRIM(RTRIM(REPLACE(j.[maintotalcount], ',', '.'))), '')) AS [maintotalcount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[mainwaprice], ',', '.'))), '')) AS [mainwaprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[maincurrentprice], ',', '.'))), '')) AS [maincurrentprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[eveopenvolume], ',', '.'))), '')) AS [eveopenvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[eveopenamount], ',', '.'))), '')) AS [eveopenamount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[eveopenprice], ',', '.'))), '')) AS [eveopenprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evelastvolume], ',', '.'))), '')) AS [evelastvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evelastamount], ',', '.'))), '')) AS [evelastamount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evelastprice], ',', '.'))), '')) AS [evelastprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evemaxdealprice], ',', '.'))), '')) AS [evemaxdealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evemindealprice], ',', '.'))), '')) AS [evemindealprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evetotalvolume], ',', '.'))), '')) AS [evetotalvolume],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evetotalamount], ',', '.'))), '')) AS [evetotalamount],
    TRY_CONVERT(bigint, NULLIF(LTRIM(RTRIM(REPLACE(j.[evetotalcount], ',', '.'))), '')) AS [evetotalcount],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evewaprice], ',', '.'))), '')) AS [evewaprice],
    TRY_CONVERT(decimal(28,8), NULLIF(LTRIM(RTRIM(REPLACE(j.[evecurrentprice], ',', '.'))), '')) AS [evecurrentprice]
  FROM dbo.stg_trade_result_msg_buffer b
  CROSS APPLY (
    SELECT *
    FROM OPENJSON(b.MessageBody, '$')
    WITH (
      [tradedate] nvarchar(512) '$[0]',
      [securityid] nvarchar(512) '$[1]',
      [isin] nvarchar(512) '$[2]',
      [secshortname] nvarchar(512) '$[3]',
      [issuername] nvarchar(512) '$[4]',
      [seccategory] nvarchar(512) '$[5]',
      [quotelist] nvarchar(512) '$[6]',
      [currencyid] nvarchar(512) '$[7]',
      [seccurrencyid] nvarchar(512) '$[8]',
      [facevalue] nvarchar(512) '$[9]',
      [settlementcurrency] nvarchar(512) '$[10]',
      [accruedinterest] nvarchar(512) '$[11]',
      [isaddress] nvarchar(512) '$[12]',
      [setttype] nvarchar(512) '$[13]',
      [trademode] nvarchar(512) '$[14]',
      [totalvolume] nvarchar(512) '$[15]',
      [totalamount] nvarchar(512) '$[16]',
      [totaldealcount] nvarchar(512) '$[17]',
      [maxdealprice] nvarchar(512) '$[18]',
      [mindealprice] nvarchar(512) '$[19]',
      [closeprice] nvarchar(512) '$[20]',
      [prevclose] nvarchar(512) '$[21]',
      [trendclose] nvarchar(512) '$[22]',
      [waprice] nvarchar(512) '$[23]',
      [marketprice2] nvarchar(512) '$[24]',
      [mp2volume] nvarchar(512) '$[25]',
      [marketprice3] nvarchar(512) '$[26]',
      [mp3volume] nvarchar(512) '$[27]',
      [currentprice] nvarchar(512) '$[28]',
      [firstcurrentprice] nvarchar(512) '$[29]',
      [trendcurrentprice] nvarchar(512) '$[30]',
      [averagedailyvolume] nvarchar(512) '$[31]',
      [clearingprice] nvarchar(512) '$[32]',
      [trendclearingprice] nvarchar(512) '$[33]',
      [mornopenvolume] nvarchar(512) '$[34]',
      [mornopenamount] nvarchar(512) '$[35]',
      [mornopenprice] nvarchar(512) '$[36]',
      [mornlastvolume] nvarchar(512) '$[37]',
      [mornlastamount] nvarchar(512) '$[38]',
      [mornlastprice] nvarchar(512) '$[39]',
      [mornmaxdealprice] nvarchar(512) '$[40]',
      [mornmindealprice] nvarchar(512) '$[41]',
      [morntotalvolume] nvarchar(512) '$[42]',
      [morntotalamount] nvarchar(512) '$[43]',
      [morntotalcount] nvarchar(512) '$[44]',
      [mornwaprice] nvarchar(512) '$[45]',
      [morncurrentprice] nvarchar(512) '$[46]',
      [mainopenvolume] nvarchar(512) '$[47]',
      [mainopenamount] nvarchar(512) '$[48]',
      [mainopenprice] nvarchar(512) '$[49]',
      [mainlastvolume] nvarchar(512) '$[50]',
      [mainlastamount] nvarchar(512) '$[51]',
      [mainlastprice] nvarchar(512) '$[52]',
      [mainmaxdealprice] nvarchar(512) '$[53]',
      [mainmindealprice] nvarchar(512) '$[54]',
      [maintotalvolume] nvarchar(512) '$[55]',
      [maintotalamount] nvarchar(512) '$[56]',
      [maintotalcount] nvarchar(512) '$[57]',
      [mainwaprice] nvarchar(512) '$[58]',
      [maincurrentprice] nvarchar(512) '$[59]',
      [eveopenvolume] nvarchar(512) '$[60]',
      [eveopenamount] nvarchar(512) '$[61]',
      [eveopenprice] nvarchar(512) '$[62]',
      [evelastvolume] nvarchar(512) '$[63]',
      [evelastamount] nvarchar(512) '$[64]',
      [evelastprice] nvarchar(512) '$[65]',
      [evemaxdealprice] nvarchar(512) '$[66]',
      [evemindealprice] nvarchar(512) '$[67]',
      [evetotalvolume] nvarchar(512) '$[68]',
      [evetotalamount] nvarchar(512) '$[69]',
      [evetotalcount] nvarchar(512) '$[70]',
      [evewaprice] nvarchar(512) '$[71]',
      [evecurrentprice] nvarchar(512) '$[72]'
    )
  ) j
  WHERE b.SessionId = @SessionId AND b.IsError = 0;
END;
