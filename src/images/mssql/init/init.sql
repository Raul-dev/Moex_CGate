CREATE     PROCEDURE [audit].[sp_LnkUpdate]
    @LogID          int,
    @EndTime        datetime2(4)  = NULL,
    @RowCount       int  = NULL,
    @TranCount      int  = NULL,
    @ProcedureInfo  varchar(max)  = NULL,
