CREATE OR REPLACE PROCEDURE load_trade_result_from_buffer(p_session_id bigint DEFAULT 0)
LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO stg_trade_result_target (
    "tradedate", "securityid", "isin", "secshortname", "issuername", "seccategory", "quotelist", "currencyid", "seccurrencyid", "facevalue", "settlementcurrency", "accruedinterest", "isaddress", "setttype", "trademode", "totalvolume", "totalamount", "totaldealcount", "maxdealprice", "mindealprice", "closeprice", "prevclose", "trendclose", "waprice", "marketprice2", "mp2volume", "marketprice3", "mp3volume", "currentprice", "firstcurrentprice", "trendcurrentprice", "averagedailyvolume", "clearingprice", "trendclearingprice", "mornopenvolume", "mornopenamount", "mornopenprice", "mornlastvolume", "mornlastamount", "mornlastprice", "mornmaxdealprice", "mornmindealprice", "morntotalvolume", "morntotalamount", "morntotalcount", "mornwaprice", "morncurrentprice", "mainopenvolume", "mainopenamount", "mainopenprice", "mainlastvolume", "mainlastamount", "mainlastprice", "mainmaxdealprice", "mainmindealprice", "maintotalvolume", "maintotalamount", "maintotalcount", "mainwaprice", "maincurrentprice", "eveopenvolume", "eveopenamount", "eveopenprice", "evelastvolume", "evelastamount", "evelastprice", "evemaxdealprice", "evemindealprice", "evetotalvolume", "evetotalamount", "evetotalcount", "evewaprice", "evecurrentprice"
  )
  SELECT
    (e.elem ->> 'tradedate'),
    (e.elem ->> 'securityid'),
    (e.elem ->> 'isin'),
    (e.elem ->> 'secshortname'),
    (e.elem ->> 'issuername'),
    (e.elem ->> 'seccategory'),
    (e.elem ->> 'quotelist'),
    (e.elem ->> 'currencyid'),
    (e.elem ->> 'seccurrencyid'),
    (e.elem ->> 'facevalue'),
    (e.elem ->> 'settlementcurrency'),
    (e.elem ->> 'accruedinterest'),
    (e.elem ->> 'isaddress'),
    (e.elem ->> 'setttype'),
    (e.elem ->> 'trademode'),
    (e.elem ->> 'totalvolume'),
    (e.elem ->> 'totalamount'),
    (e.elem ->> 'totaldealcount'),
    (e.elem ->> 'maxdealprice'),
    (e.elem ->> 'mindealprice'),
    (e.elem ->> 'closeprice'),
    (e.elem ->> 'prevclose'),
    (e.elem ->> 'trendclose'),
    (e.elem ->> 'waprice'),
    (e.elem ->> 'marketprice2'),
    (e.elem ->> 'mp2volume'),
    (e.elem ->> 'marketprice3'),
    (e.elem ->> 'mp3volume'),
    (e.elem ->> 'currentprice'),
    (e.elem ->> 'firstcurrentprice'),
    (e.elem ->> 'trendcurrentprice'),
    (e.elem ->> 'averagedailyvolume'),
    (e.elem ->> 'clearingprice'),
    (e.elem ->> 'trendclearingprice'),
    (e.elem ->> 'mornopenvolume'),
    (e.elem ->> 'mornopenamount'),
    (e.elem ->> 'mornopenprice'),
    (e.elem ->> 'mornlastvolume'),
    (e.elem ->> 'mornlastamount'),
    (e.elem ->> 'mornlastprice'),
    (e.elem ->> 'mornmaxdealprice'),
    (e.elem ->> 'mornmindealprice'),
    (e.elem ->> 'morntotalvolume'),
    (e.elem ->> 'morntotalamount'),
    (e.elem ->> 'morntotalcount'),
    (e.elem ->> 'mornwaprice'),
    (e.elem ->> 'morncurrentprice'),
    (e.elem ->> 'mainopenvolume'),
    (e.elem ->> 'mainopenamount'),
    (e.elem ->> 'mainopenprice'),
    (e.elem ->> 'mainlastvolume'),
    (e.elem ->> 'mainlastamount'),
    (e.elem ->> 'mainlastprice'),
    (e.elem ->> 'mainmaxdealprice'),
    (e.elem ->> 'mainmindealprice'),
    (e.elem ->> 'maintotalvolume'),
    (e.elem ->> 'maintotalamount'),
    (e.elem ->> 'maintotalcount'),
    (e.elem ->> 'mainwaprice'),
    (e.elem ->> 'maincurrentprice'),
    (e.elem ->> 'eveopenvolume'),
    (e.elem ->> 'eveopenamount'),
    (e.elem ->> 'eveopenprice'),
    (e.elem ->> 'evelastvolume'),
    (e.elem ->> 'evelastamount'),
    (e.elem ->> 'evelastprice'),
    (e.elem ->> 'evemaxdealprice'),
    (e.elem ->> 'evemindealprice'),
    (e.elem ->> 'evetotalvolume'),
    (e.elem ->> 'evetotalamount'),
    (e.elem ->> 'evetotalcount'),
    (e.elem ->> 'evewaprice'),
    (e.elem ->> 'evecurrentprice')
  FROM stg_trade_result_msg_buffer b
  CROSS JOIN LATERAL jsonb_array_elements(b.message_body::jsonb) AS e(elem)
  WHERE b.session_id = p_session_id AND b.is_error = false;
END;
$$;
