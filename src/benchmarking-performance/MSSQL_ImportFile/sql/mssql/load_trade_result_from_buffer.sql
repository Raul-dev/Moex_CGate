    [eveopenvolume] nvarchar(512) '$.eveopenvolume',
    [eveopenamount] nvarchar(512) '$.eveopenamount',
    [eveopenprice] nvarchar(512) '$.eveopenprice',
    [evelastvolume] nvarchar(512) '$.evelastvolume',
    [evelastamount] nvarchar(512) '$.evelastamount',
    [evelastprice] nvarchar(512) '$.evelastprice',
    [evemaxdealprice] nvarchar(512) '$.evemaxdealprice',
    [evemindealprice] nvarchar(512) '$.evemindealprice',
    [evetotalvolume] nvarchar(512) '$.evetotalvolume',
