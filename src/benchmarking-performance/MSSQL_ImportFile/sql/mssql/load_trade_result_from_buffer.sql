    [facevalue] nvarchar(512) '$.facevalue',
    [settlementcurrency] nvarchar(512) '$.settlementcurrency',
    [accruedinterest] nvarchar(512) '$.accruedinterest',
    [isaddress] nvarchar(512) '$.isaddress',
    [setttype] nvarchar(512) '$.setttype',
